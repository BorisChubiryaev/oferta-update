/** Пользовательское сообщение: инструкция + карта Оферты + черновик алгоритма. */
export function buildUserPrompt(req: AiParseRequest): string {
  const parts: string[] = [];

  parts.push("КАРТА ОФЕРТЫ (какие координаты существуют):");
  parts.push(req.offerDigest);
  parts.push("");

  if (req.tables?.length) {
    parts.push("ТАБЛИЦЫ РЯДОМ С ИНСТРУКЦИЕЙ (содержимое правки часто лежит здесь, а не в кавычках):");
    req.tables.forEach((tbl, i) => {
      parts.push(`  Таблица ${i + 1}:`);
      // Больше десяти строк модели не нужно: она определяет, ЧТО это за
      // таблица и какие колонки в ней, а сами строки движок возьмёт из docx
      // сам — по тем же данным, но без риска, что модель их перепишет.
      for (const row of tbl.slice(0, 10)) parts.push(`    | ${row.join(" | ")}`);
      if (tbl.length > 10) parts.push(`    … ещё ${tbl.length - 10} строк`);
    });
    parts.push("");
  }

  if (req.mode === "verify" && req.algorithmDraft) {
    parts.push("ЧЕРНОВИК АЛГОРИТМА (проверь его; если он верен — верни его же):");
    parts.push(JSON.stringify(req.algorithmDraft, null, 2));
    parts.push("");
    parts.push(
      "Если черновик правильно определил тип, цель и текст правки — верни его без изменений. " +
        "Если алгоритм ошибся в координатах — верни исправленный вариант и объясни в reasoning, что именно было не так.",
    );
    parts.push("");
  }

  parts.push("ИНСТРУКЦИЯ ДЛЯ РАЗБОРА:");
  parts.push("---");
  parts.push(req.instruction);
  parts.push("---");
  return parts.join("\n");
}
