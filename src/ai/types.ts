// Общие типы гибридного разбора.
import type { Operation } from "@/engine/types";

/**
 * Откуда взялась операция.
 *
 * Показывается оператору и попадает в отчёт: правка, предложенная моделью,
 * и правка, разобранная по формальному правилу, требуют разного внимания, и
 * скрывать эту разницу нельзя.
 */
export type Provenance =
  /** Детерминированный разбор справился сам — ИИ не спрашивали. */
  | "algorithm"
  /** Алгоритм не справился; операцию предложила модель и приняла проверка. */
  | "ai"
  /** Алгоритм разобрал, модель подтвердила координаты (второе мнение сошлось). */
  | "algorithm+ai"
  /** Модель предложила другое прочтение, чем алгоритм, — нужен оператор. */
  | "conflict"
  /** Ни алгоритм, ни модель не дали применимой операции. */
  | "manual";

export interface HybridOperation {
  op: Operation;
  provenance: Provenance;
  /** Номер инструкции в исходном документе (0-based). */
  unitIndex: number;
  /** Пояснение модели своими словами — для оператора, не для движка. */
  aiReasoning?: string;
  /** Альтернативное прочтение, если алгоритм и модель разошлись. */
  alternative?: Operation;
  /** Результат сухого прогона операции по Оферте. */
  dryRun?: { ok: boolean; message: string };
}

export interface HybridResult {
  operations: HybridOperation[];
  /** Сводка по источникам — для шапки экрана проверки. */
  stats: Record<Provenance, number>;
  /** Что пошло не так с ИИ (сеть, ключ, лимит) — работа при этом не падает. */
  aiErrors: string[];
  /** Обращались ли к модели вообще. */
  aiUsed: boolean;
}

/** Запрос к /api/ai/parse. */
export interface AiParseRequest {
  /** Текст инструкции (одна единица разбора). */
  instruction: string;
  /** Таблицы, идущие рядом с инструкцией (уже как текст ячеек). */
  tables?: string[][][];
  /** Структурная выжимка Оферты — координаты, по которым модель ориентируется. */
  offerDigest: string;
  /**
   * Что предложил алгоритм, если предложил. Модель работает вторым мнением:
   * ей показывают черновик, а не просят угадать с нуля.
   */
  algorithmDraft?: unknown;
  /** Режим: разбор с нуля или проверка чужого черновика. */
  mode: "parse" | "verify";
}

export interface AiParseResponse {
  /** Операции в «сыром» виде — до проверки схемой. */
  operations: unknown[];
  /** Своими словами: что модель поняла. Показывается оператору. */
  reasoning?: string;
  /** Уверенность модели 0..1. */
  confidence?: number;
  /** Модель, которая реально ответила (OpenRouter может подменить :free). */
  model?: string;
}
