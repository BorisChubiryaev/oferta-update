// Доменная модель genOferta.
//
// Инструкции из документов «Изменения» разбираются (ИИ или оффлайн-парсером)
// в СТРУКТУРНЫЕ операции. Юридический текст Оферты меняет только
// детерминированный движок — модель лишь указывает координаты правки.

/** Куда направлена правка внутри Оферты. */
export type OpTarget =
  /** Сноска № N (нумерация — по порядку ссылок в тексте). */
  | {
      kind: "footnote";
      number: number;
      label?: string;
      /** Сноска задана не номером, а пунктом: «сноска к пункту 5.3». */
      atPoint?: string;
    }
  /** Термин из раздела «Термины» (напр. п. 2.44 «Устройство»). */
  | { kind: "term"; section?: string; point?: string; term: string }
  /** Обычный пункт основного текста (напр. п. 7.6). */
  | { kind: "point"; section?: string; point: string; heading?: string }
  /** Преамбула Оферты — вводный абзац до раздела 1. */
  | { kind: "preamble" }
  /** Пункт внутри Приложения (напр. Приложение №2 п. 1.2). */
  | { kind: "appendix_point"; appendix: string; point: string }
  /** Таблица внутри Приложения (напр. таблица п. 3 Приложения №2, либо вся таблица Приложения №1). */
  | { kind: "appendix_table"; appendix: string; point?: string };

/** Тип операции над Офертой. */
export type OpType =
  | "insert_after"
  | "replace"
  | "replace_footnote"
  | "add_footnote" // добавить новую сноску (нумерация сносок сдвигается автоматически)
  | "insert_point" // добавить новый пункт (нумерация сдвигается автоматически)
  | "append_table_rows"
  | "replace_table_rows"
  | "sort_table_alpha" // пересортировать таблицу приложения по алфавиту
  | "insert_table_row_alpha" // вставить строку в таблицу по алфавиту
  | "insert_before" // вставить текст перед указанными словами
  | "replace_sentence" // изложить предложение пункта в новой редакции
  | "replace_paragraph" // изложить абзац пункта в новой редакции
  | "append_sentence" // дополнить пункт предложением
  | "append_paragraph" // дополнить пункт абзацем
  | "replace_words" // заменить слово/фразу внутри пункта
  | "delete_words" // удалить слова внутри пункта
  | "replace_words_global" // заменить слова по всему тексту документа
  | "delete_paragraph" // исключить абзац пункта
  | "delete_footnote" // исключить сноску (последующие перенумеровываются)
  | "delete_point" // исключить пункт (с перенумерацией последующих)
  | "manual"; // распознано, но требует ручной обработки

/** Одна распознанная правка. */
export interface Operation {
  /** Стабильный идентификатор в рамках сессии. */
  id: string;
  /** Из какого документа «Изменения» пришла правка (имя файла). */
  sourceDoc: string;
  /** Тип операции. */
  type: OpType;
  /** Цель правки в Оферте. */
  target: OpTarget;
  /** Якорная фраза «после слов …» (для insert_after). */
  anchor?: string;
  /** Что искать внутри пункта (для replace_words / delete_words). */
  find?: string;
  /** Номер предложения в пункте: 1 — первое, -1 — последнее. */
  sentenceIndex?: number;
  /** Номер абзаца в пункте: 1 — первый, -1 — последний. */
  paragraphIndex?: number;
  /** Вставляемый / заменяющий текст (уже без внешних кавычек-ёлочек). */
  payload?: string;
  /** Строки таблицы (для append/replace_table_rows): массив строк, каждая — массив ячеек. */
  rows?: string[][];
  /** Диапазон номеров добавляемых строк, если указан в инструкции. */
  rowRange?: { from: number; to: number };
  /** Номера заменяемых строк таблицы (для replace_table_rows). */
  rowNumbers?: number[];
  /** Индекс колонки с наименованием для алфавитных операций (по умолчанию 1). */
  nameColumn?: number;
  /** Пояснение для операций типа manual / неуверенного распознавания. */
  note?: string;
  /** Нужна ли последующая перенумерация сносок. */
  renumberFootnotes?: boolean;
  /** Нужна ли перенумерация последующих пунктов (Word делает её сам). */
  renumberPoints?: boolean;
  /** Исходный текст инструкции — показывается оператору и попадает в объединённый файл. */
  rawText: string;
  /** Уверенность парсера 0..1 (для сортировки внимания оператора). */
  confidence: number;
  /** Предупреждения парсера (напр. «якорь не найден дословно»). */
  warnings?: string[];
}

/** Результат применения одной операции. */
export interface ApplyResult {
  operationId: string;
  ok: boolean;
  message: string;
  /** Позиция цели в теле Оферты — ключ сортировки «по порядку следования пунктов». */
  orderKey: number;
  /**
   * Текст ДО правки («было») — для показа в объединённом файле изменений и
   * операторского контроля. Заполняется, когда движок реально заменяет или
   * удаляет существующий текст (для чистых вставок/добавлений — не нужен).
   */
  oldText?: string;
  /** Текст ПОСЛЕ правки («стало»), парный к oldText. */
  newText?: string;
}

/** Итог полной сборки. */
export interface BuildResult {
  /** docx актуального текста Оферты с выделенными изменениями. */
  offerDocx: Uint8Array;
  /** docx объединённого файла с описанием изменений (в порядке Оферты). */
  combinedDocx: Uint8Array;
  /** Пооперационный отчёт. */
  results: ApplyResult[];
  /** Порядок операций после сортировки. */
  orderedOperationIds: string[];
}

/** Режим выделения изменений в итоговой Оферте. */
export type HighlightMode = "color" | "tracked" | "both";

export interface BuildOptions {
  /** Как показывать изменения. По умолчанию — цветом (как в образце). */
  highlightMode?: HighlightMode;
  /** Цвет шрифта для выделения (hex без #). По умолчанию — как в образце. */
  highlightColor?: string;
  /** Автор правок для режима рецензирования. */
  author?: string;
  /**
   * Показывать ли прежний текст зачёркнутым рядом с новой редакцией.
   * По умолчанию true (как было). При false в режиме цвета остаётся только
   * итоговая редакция — прежний текст не выводится. В режиме рецензирования
   * прежний текст сохраняется всегда: без записи об удалении отклонение правки
   * в Word не восстановит исходный текст.
   */
  showOld?: boolean;
}
